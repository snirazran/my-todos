import fs from 'node:fs';
import path from 'node:path';

const SRC = path.resolve('src');
const OUT = path.resolve('src/lib/generated/analyticsManifest.ts');
const EVENTS_FILE = path.resolve('src/lib/analytics/events.ts');

function declaredEvents() {
  const text = fs.readFileSync(EVENTS_FILE, 'utf8');
  const block = text.split('export const ANALYTICS_EVENTS = [')[1].split('] as const;')[0];
  return [...block.matchAll(/'([a-z0-9_]+)'/g)].map((match) => match[1]);
}

function sourceFiles(dir, acc = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) sourceFiles(full, acc);
    else if (/\.tsx?$/.test(entry.name)) acc.push(full);
  }
  return acc;
}

// A name only counts as wired when it appears somewhere that is not the
// taxonomy itself or the reporting layer that reads it back.
const IGNORED = [
  path.join('lib', 'analytics', 'events.ts'),
  path.join('lib', 'analytics', 'catalog.ts'),
  path.join('lib', 'analytics', 'signals.ts'),
  path.join('lib', 'analytics', 'report'),
  path.join('lib', 'generated', 'analyticsManifest.ts'),
  path.join('app', 'admin', 'statistics'),
  path.join('app', 'api', 'admin', 'statistics'),
  path.join('components', 'admin', 'statistics'),
];

function build() {
  const events = declaredEvents();
  const files = sourceFiles(SRC).filter(
    (file) => !IGNORED.some((ignored) => file.includes(ignored)),
  );

  const wired = new Map();
  for (const file of files) {
    const text = fs.readFileSync(file, 'utf8');
    for (const event of events) {
      if (wired.has(event)) continue;
      if (text.includes(`'${event}'`) || text.includes(`"${event}"`)) {
        wired.set(event, path.relative(process.cwd(), file));
      }
    }
  }

  const unwired = events.filter((event) => !wired.has(event));

  const body = `// Generated by scripts/generate-analytics-manifest.mjs — do not edit by hand.
// Regenerate with: node scripts/generate-analytics-manifest.mjs

/** Declared events that have at least one emit site in the codebase. */
export const WIRED_EVENTS = new Set<string>(${JSON.stringify([...wired.keys()].sort(), null, 2)});

/** Where each wired event is emitted, for tracing a silent event back to code. */
export const EVENT_EMIT_SITES: Record<string, string> = ${JSON.stringify(
    Object.fromEntries([...wired.entries()].sort(([a], [b]) => a.localeCompare(b))),
    null,
    2,
  )};

export const MANIFEST_GENERATED_AT = '${new Date().toISOString()}';
`;

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, body);

  console.log(`analytics manifest: ${wired.size} wired, ${unwired.length} declared but never emitted`);
  if (unwired.length) console.log(`  unwired: ${unwired.join(', ')}`);
}

build();
