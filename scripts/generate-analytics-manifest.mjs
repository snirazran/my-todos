import fs from 'node:fs';
import path from 'node:path';

const SRC = path.resolve('src');
const OUT = path.resolve('src/lib/generated/analyticsManifest.ts');
const EVENTS_FILE = path.resolve('src/lib/analytics/events.ts');

function declaredEvents() {
  const text = fs.readFileSync(EVENTS_FILE, 'utf8');
  const block = text.split('export const ANALYTICS_EVENTS = [')[1].split('] as const;')[0];
  return [...block.matchAll(/'([a-z0-9_]+)'/g)].map((match) => match[1]);
}

function sourceFiles(dir, acc = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) sourceFiles(full, acc);
    else if (/\.tsx?$/.test(entry.name)) acc.push(full);
  }
  return acc;
}

// A name only counts as wired when it appears somewhere that is not the
// taxonomy itself or the reporting layer that reads it back.
const IGNORED = [
  path.join('lib', 'analytics', 'events.ts'),
  path.join('lib', 'analytics', 'catalog.ts'),
  path.join('lib', 'analytics', 'signals.ts'),
  path.join('lib', 'analytics', 'report'),
  path.join('lib', 'generated', 'analyticsManifest.ts'),
  path.join('app', 'admin', 'statistics'),
  path.join('app', 'api', 'admin', 'statistics'),
  path.join('components', 'admin', 'statistics'),
];

/**
 * The transport route lists every client event name in its allowlist, so a
 * plain name search would attribute all of them there and hide the real emit
 * site. It still proves the name is routable, so it counts as wired — just
 * never as the source.
 */
const TRANSPORT = path.join('app', 'api', 'analytics', 'route.ts');

function emitSitesIn(text, event) {
  // Prefer a real call: trackAnalyticsEvent('x') / name: 'x' next to a record call.
  const direct = new RegExp(
    `(?:trackAnalyticsEvent|recordAnalyticsEvent)\\s*\\(\\s*[{\\s]*(?:[^)]{0,200}?name:\\s*)?['"]${event}['"]`,
    's',
  );
  if (direct.test(text)) return 'call';
  // A mapping table or a switch that returns the name (campaign events, the
  // RevenueCat webhook) is an emit site just as much as a direct call.
  if (new RegExp(`['"]${event}['"]\\s*(?:,|\\]|\\}|:|;)`).test(text)) return 'reference';
  if (new RegExp(`return\\s+['"]${event}['"]`).test(text)) return 'reference';
  return null;
}

function build() {
  const events = declaredEvents();
  const files = sourceFiles(SRC).filter(
    (file) => !IGNORED.some((ignored) => file.includes(ignored)),
  );

  const calls = new Map();
  const references = new Map();
  const routable = new Set();

  for (const file of files) {
    const text = fs.readFileSync(file, 'utf8');
    const relative = path.relative(process.cwd(), file);
    const isTransport = file.includes(TRANSPORT);

    for (const event of events) {
      const kind = emitSitesIn(text, event);
      if (!kind) continue;
      if (isTransport) {
        routable.add(event);
        continue;
      }
      if (kind === 'call' && !calls.has(event)) calls.set(event, relative);
      else if (kind === 'reference' && !references.has(event)) references.set(event, relative);
    }
  }

  const sites = new Map();
  for (const event of events) {
    const site = calls.get(event) ?? references.get(event);
    if (site) sites.set(event, site);
  }

  const unwired = events.filter((event) => !sites.has(event));
  const transportOnly = unwired.filter((event) => routable.has(event));

  const body = `// Generated by scripts/generate-analytics-manifest.mjs — do not edit by hand.
// Regenerate with: pnpm analytics:manifest

/** Declared events that have at least one emit site in the codebase. */
export const WIRED_EVENTS = new Set<string>(${JSON.stringify([...sites.keys()].sort(), null, 2)});

/** Where each wired event is emitted, for tracing a silent event back to code. */
export const EVENT_EMIT_SITES: Record<string, string> = ${JSON.stringify(
    Object.fromEntries([...sites.entries()].sort(([a], [b]) => a.localeCompare(b))),
    null,
    2,
  )};

export const MANIFEST_GENERATED_AT = '${new Date().toISOString()}';
`;

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, body);

  console.log(
    `analytics manifest: ${sites.size} wired (${calls.size} direct calls, ${references.size} via a mapping table), ${unwired.length} unwired`,
  );
  if (unwired.length) console.log(`  unwired: ${unwired.join(', ')}`);
  if (transportOnly.length) {
    console.log(`  allowlisted on /api/analytics but never emitted: ${transportOnly.join(', ')}`);
  }
}

build();
